// Embeds each runtime as a string, since a bundle does not keep the file beside the host

import fs from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(fileURLToPath(new URL('../', import.meta.url)));
const LAMBDA = path.join(ROOT, 'src', 'lambda');
const RUNTIMES = [
  ['process-runtime.ts', 'process-runtime.generated.ts', 'PROCESS_RUNTIME_SOURCE'],
  ['worker-runtime.ts', 'worker-runtime.generated.ts', 'WORKER_RUNTIME_SOURCE'],
];

// Build-time only, so the experimental warning is noise
process.removeAllListeners('warning');

for (const [source, output, name] of RUNTIMES) {
  const runtime = stripTypeScriptTypes(fs.readFileSync(path.join(LAMBDA, source), 'utf8'));
  const generated = `// Generated by scripts/embed-runtime.mjs from ${source}. Do not edit.
export const ${name}: string = ${JSON.stringify(runtime)};
`;
  const target = path.join(LAMBDA, output);
  // Rewriting identical bytes still moves mtime, which vitest watches
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated) {
    fs.writeFileSync(target, generated);
  }
}
